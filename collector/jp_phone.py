def phone_digits(phone: str) -> str:
    """数字だけを取り出す。全角数字も半角にそろえる。"""
    text = unicodedata.normalize("NFKC", phone or "")
    return _DIGIT.sub("", text)


def format_jp_phone(phone: str) -> str:
    """0757087200 → 075-708-7200 のようにハイフンを付ける。"""
    raw = (phone or "").strip()
    digits = phone_digits(raw)
    if len(digits) < 10:
        return raw

    if digits.startswith(("090", "080", "070", "050")) and len(digits) == 11:
        return f"{digits[:3]}-{digits[3:7]}-{digits[7:]}"
    if digits.startswith(("0120", "0800", "0570", "0990")) and len(digits) in (10, 11):
        return f"{digits[:4]}-{digits[4:7]}-{digits[7:]}"
    if digits.startswith(("03", "06")) and len(digits) == 10:
        return f"{digits[:2]}-{digits[2:6]}-{digits[6:]}"
    if len(digits) == 10:
        if digits[:5] in _AREA_5:
            return f"{digits[:5]}-{digits[5:6]}-{digits[6:]}"
        if digits[:4] in _AREA_4:
            return f"{digits[:4]}-{digits[4:6]}-{digits[6:]}"
        return f"{digits[:3]}-{digits[3:6]}-{digits[6:]}"
    if len(digits) == 11:
        return f"{digits[:3]}-{digits[3:7]}-{digits[7:]}"
    return raw
